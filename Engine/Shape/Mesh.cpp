#include "Mesh.h"

Mesh Mesh::CreateCube()
{
    Mesh mesh;

    mesh.vertices =
    {
        {-0.5f, -0.5f, -0.5f}, 
        { 0.5f, -0.5f, -0.5f}, 
        { 0.5f,  0.5f, -0.5f}, 
        {-0.5f,  0.5f, -0.5f}, 
        {-0.5f, -0.5f,  0.5f}, 
        { 0.5f, -0.5f,  0.5f}, 
        { 0.5f,  0.5f,  0.5f}, 
        {-0.5f,  0.5f,  0.5f}  
    };

    /* Triangles 인덱스 순서 */
    mesh.triangles =
    {
        {{0, 3, 2}},
        {{0, 2, 1}},

        {{4, 5, 6}},
        {{4, 6, 7}},

        {{0, 4, 7}},
        {{0, 7, 3}},

        {{1, 2, 6}},
        {{1, 6, 5}},

        {{0, 1, 5}},
        {{0, 5, 4}},

        {{3, 7, 6}},
        {{3, 6, 2}}
    };

    return mesh;
}